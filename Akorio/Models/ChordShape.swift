    private static func sourceShape(_ frets: [Int], baseFret: Int) -> ChordShape {
        ChordShape(
            frets: frets.map { fret in
                guard fret >= 0 else { return nil }
                return fret == 0 ? 0 : baseFret + fret - 1
            },
            baseFret: baseFret
        )
    }

    private static func absoluteShape(_ frets: [Int?], baseFret: Int) -> ChordShape {
        ChordShape(frets: frets, baseFret: baseFret)
    }

    static func shape(for label: String) -> ChordShape {
        shapes[label] ?? ChordShape(frets: Array(repeating: nil, count: 6), baseFret: 1)
    }

    static func shape(root: String, quality: ChordQuality) -> ChordShape? {
        shapes[ChordIdentity(root: root, quality: quality).label]
    }

